# ---------------- x-polynomial primitives (index = x-degree) ----------
def ps(f):
    while f and f[-1] == 0:
        f.pop()
    return f


def padd(f, g):
    n = max(len(f), len(g))
    return ps([(f[i] if i < len(f) else 0) + (g[i] if i < len(g) else 0)
               for i in range(n)])


def psub(f, g):
    n = max(len(f), len(g))
    return ps([(f[i] if i < len(f) else 0) - (g[i] if i < len(g) else 0)
               for i in range(n)])


def pmul(f, g):
    if not f or not g:
        return []
    out = [0] * (len(f) + len(g) - 1)
    for i, a in enumerate(f):
        if a:
            for j, b in enumerate(g):
                out[i + j] += a * b
    return ps(out)


def pdm(f, g):
    """divmod by monic g."""
    f = list(f)
    assert g and g[-1] == 1
    dg = len(g) - 1
    q = [0] * max(1, len(f) - dg)
    while ps(f) and len(f) - 1 >= dg:
        d = len(f) - 1 - dg
        c = f[-1]
        q[d] += c
        for k in range(len(g)):
            f[d + k] -= c * g[k]
    return ps(q), ps(f)


def ppow(f, n):
    r = [1]
    for _ in range(n):
        r = pmul(r, f)
    return r


def vp(n, p):
    assert n != 0
    n, v = abs(n), 0
    while n % p == 0:
        n //= p
        v += 1
    return v



def res_euclid(f, g):
    """Exact resultant, Euclidean route over Fractions."""
    f = [Fraction(c) for c in f]
    g = [Fraction(c) for c in g]

    def st(h):
        while h and h[-1] == 0:
            h.pop()
        return h
    f, g = st(f), st(g)
    r = Fraction(1)
    while True:
        if not g:
            return Fraction(0)
        if len(g) == 1:
            return r * g[0] ** (len(f) - 1)
        if len(f) < len(g):
            f, g = g, f
            if (len(f) - 1) * (len(g) - 1) % 2 == 1:
                r = -r
            continue
        df, dg = len(f) - 1, len(g) - 1
        lead = g[-1]
        h = list(f)
        while st(h) and len(h) - 1 >= dg:
            d = len(h) - 1 - dg
            c = h[-1] / lead
            for k in range(len(g)):
                h[d + k] -= c * g[k]
            st(h)
        dr = len(h) - 1 if h else -1
        r *= lead ** (df - (dr if dr >= 0 else 0))
        if df * dg % 2 == 1:
            r = -r
        if not h:
            return Fraction(0)
        f, g = g, h


def sylvester(f, g):
    df, dg = len(f) - 1, len(g) - 1
    n = df + dg
    M = []
    for i in range(dg):
        M.append([0] * i + list(reversed(f)) + [0] * (n - df - 1 - i))
    for i in range(df):
        M.append([0] * i + list(reversed(g)) + [0] * (n - dg - 1 - i))
    return M


def bareiss(M):
    M = [row[:] for row in M]
    n = len(M)
    prev = 1
    sign = 1
    for k in range(n - 1):
        if M[k][k] == 0:
            for r in range(k + 1, n):
                if M[r][k] != 0:
                    M[k], M[r] = M[r], M[k]
                    sign = -sign
                    break
            else:
                return 0
        for i in range(k + 1, n):
            for j in range(k + 1, n):
                M[i][j] = (M[i][j] * M[k][k] - M[i][k] * M[k][j]) // prev
        prev = M[k][k]
    return sign * M[n - 1][n - 1]


def smith_vals(M, p):
    """Elementary-divisor p-valuations of an integer matrix, via
    Z_(p)-elimination (pivot = min-valuation entry; unit parts are
    invertible in the localization — Fractions with p-coprime
    denominators)."""
    A = [[Fraction(x) for x in row] for row in M]

    def vf(x):
        num, den = abs(x.numerator), x.denominator
        return vp(num, p) - vp(den, p) if num else None
    vals = []
    while A and A[0]:
        best = None
        for i in range(len(A)):
            for j in range(len(A[0])):
                v = vf(A[i][j])
                if v is not None and (best is None or v < best[0]):
                    best = (v, i, j)
        if best is None:
            break
        v, bi, bj = best
        vals.append(v)
        A[0], A[bi] = A[bi], A[0]
        for row in A:
            row[0], row[bj] = row[bj], row[0]
        piv = A[0][0]
        for i in range(1, len(A)):
            fac = A[i][0] / piv
            A[i] = [A[i][j] - fac * A[0][j] for j in range(len(A[0]))]
        A = [row[1:] for row in A[1:]]
    return sorted(vals)


def n0_chain(cs, Hblock):
    """The rider's step bookkeeping: returns list of dicts per step."""
    out = []
    M = Hblock
    for c in cs:
        k = max(c + 1, M)
        N0 = c + max(c, M) + 1
        H = k + c
        out.append(dict(c=c, M=M, k=k, N0=N0, H=H,
                        case=('c+1' if c + 1 > M else 'M')))
        M = max(H, Hblock)
    return out



    hist_census = {}               # len(hist) -> count
    max_depth_seen = 0
    sig = {'split': 0, 'inert': 0, 'ram': 0, None: 0}
    w10tie_bad = 0
    for a0 in els:
        for a1 in els:
            total += 1
            rec = classify_full(R, q, a0, a1)
            key = (rec['kind'], rec['params'])
            counts[key] = counts.get(key, 0) + 1

def predict(q, N):
    """Closed-form window-N counts per (kind, params), PER CENTER for the
    deep families and WHOLE-SPACE for SEP-*; an independent implementation
    of the node recursion (S2.5), NOT the classifier."""
    out = {}

    def add(key, cnt):
        if cnt:
            out[key] = out.get(key, 0) + cnt

    def node(lo0, lo1, mult):
        # space C(lo0, lo1) inside (O/pi^N)^2, arriving multiplicity mult
        for u in range(lo0, N):
            if u % 2 == 1:
                kk = (u + 1) // 2
                add(('RAM', (u,)),
                    mult * (q - 1) * q ** (N - 1 - u)
                    * q ** (N - max(lo1, kk)))
                # two-sided part with w < kk handled below
                for w in range(lo1, kk):
                    add(('2SIDED', (w, u - w)),
                        mult * (q - 1) ** 2 * q ** (2 * N - 2 - u - w))
            else:
                kk = u // 2
                assert kk >= lo1, 'node invariant k >= lo1 broken'
                for w in range(lo1, kk):
                    add(('2SIDED', (w, u - w)),
                        mult * (q - 1) ** 2 * q ** (2 * N - 2 - u - w))
                cell = q ** (N - u - 1) * q ** (N - kk - 1)
                add(('SPLITEQ', (kk,)),
                    mult * ((q - 1) * (q - 2) // 2) * cell)
                add(('INERTDEEP', (kk,)),
                    mult * (q * (q - 1) // 2) * cell)
                # refinement: q-1 letters, each a full C(2k+1, k+1)
                node(u + 1, kk + 1, mult * (q - 1))
        # u >= N (A0 = 0 in the window)
        for w in range(lo1, N):
            if 2 * w + 1 <= N:
                add(('SPLIT-TAIL', (w,)),
                    mult * (q - 1) * q ** (N - 1 - w))
            else:
                add(('UNDECIDED', ()), mult * (q - 1) * q ** (N - 1 - w))
        add(('UNDECIDED', ()), mult)      # A1 = 0 too

    node(1, 1, 1)
    return out



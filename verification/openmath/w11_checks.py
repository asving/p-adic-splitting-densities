def is_square(K, q, z):
    """z in K^*: is z a square?  (odd q only)."""
    r = K.one()
    for _ in range((q - 1) // 2):
        r = K.mul(r, z)
    return r == K.one()


def abs_trace2(K, k, z):
    """absolute trace F_{2^k} -> F_2 as 0/1: sum z^(2^i)."""
    t, cur = K.zero(), z
    for _ in range(k):
        t = K.add(t, cur)
        cur = K.mul(cur, cur)
    return not K.is_zero(t)      # True <=> Tr = 1



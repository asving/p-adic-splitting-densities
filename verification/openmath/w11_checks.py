def sep_sigma(R, q, a0b, a1b):
    """fbar separable: 'split' (two roots in F_q) or 'inert'."""
    K = R.K
    if R.p == 2:
        # char 2, a1b != 0: Artin-Schreier: split iff Tr(a0b/a1b^2) = 0
        d = K.mul(a0b, K.inv(K.mul(a1b, a1b)))
        return 'inert' if abs_trace2(K, R.k, d) else 'split'
    four = K.add(K.add(K.one(), K.one()), K.add(K.one(), K.one()))
    disc = K.add(K.mul(a1b, a1b), K.neg(K.mul(four, a0b)))
    return 'split' if is_square(K, q, disc) else 'inert'


def classify_full(R, q, a0, a1):
    """The full recursive n=2 read of f = x^2 + a1 x + a0 over R = O/pi^N.
    Returns dict: kind, params, hist, center (repr), sigma, vd
    (predicted v(disc) for Zp rows; None when not determined/needed)."""
    K, k, N = R.K, R.k, R.N
    a0b, a1b = R.res(a0, 0), R.res(a1, 0)
    # ---- level 0
    if R.p == 2:
        if not K.is_zero(a1b):
            return {'kind': 'SEP-' + sep_sigma(R, q, a0b, a1b).upper(),
                    'params': (), 'hist': (), 'center': None,
                    'sigma': sep_sigma(R, q, a0b, a1b), 'vd': 0}
        cb = W10.sqrt_char2(K, a0b, k)
    else:
        four = K.add(K.add(K.one(), K.one()), K.add(K.one(), K.one()))
        disc = K.add(K.mul(a1b, a1b), K.neg(K.mul(four, a0b)))
        if not K.is_zero(disc):
            sg = sep_sigma(R, q, a0b, a1b)
            return {'kind': 'SEP-' + sg.upper(), 'params': (), 'hist': (),
                    'center': None, 'sigma': sg, 'vd': 0}
        cb = K.neg(K.mul(a1b, K.inv(K.add(K.one(), K.one()))))
    c = R.lift(cb)
    two_c = R.add(c, c)
    A1 = R.add(a1, two_c)
    A0 = R.add(R.add(R.mul(c, c), R.mul(a1, c)), a0)
    hist = []
    # pi powers for refinement shifts
    piw = R.pi()

    def pipow(m):
        r = None
        for _ in range(m):
            r = piw if r is None else R.mul(r, piw)
        return r

    while True:
        u, w = R.val(A0), R.val(A1)
        base = {'hist': tuple(hist), 'center': repr(cb)}
        if u is not None:
            if u % 2 == 1 and (w is None or 2 * w >= u + 1):
                kk = (u + 1) // 2
                if R.kind == 'Zp':
                    if R.p != 2:
                        vd = u
                    else:
                        vd = u + 1 if w == kk else u + 2
                else:
                    vd = None
                base.update({'kind': 'RAM', 'params': (u,), 'sigma': 'ram',
                             'vd': vd, 'w': w})
                return base
            if w is not None and 2 * w < u:
                base.update({'kind': '2SIDED', 'params': (w, u - w),
                             'sigma': 'split',
                             'vd': 2 * w if R.kind == 'Zp' else None})
                return base
            # u = 2k even, w >= k (or None): the e=1 residual read
            kk = u // 2
            c1 = R.res(A1, kk) if (w is not None and w == kk) else K.zero()
            c0 = R.res(A0, u)
            assert not K.is_zero(c0)
            if R.p == 2:
                if not K.is_zero(c1):
                    d = K.mul(c0, K.inv(K.mul(c1, c1)))
                    sg = 'inert' if abs_trace2(K, R.k, d) else 'split'
                    zb = None
                else:
                    sg, zb = None, W10.sqrt_char2(K, c0, k)
            else:
                four = K.add(K.add(K.one(), K.one()),
                             K.add(K.one(), K.one()))
                dR = K.add(K.mul(c1, c1), K.neg(K.mul(four, c0)))
                if not K.is_zero(dR):
                    sg, zb = ('split' if is_square(K, q, dR) else 'inert'), \
                             None
                else:
                    sg, zb = None, K.neg(K.mul(c1, K.inv(K.add(K.one(),
                                                               K.one()))))
            if sg is not None:
                base.update({'kind': 'SPLITEQ' if sg == 'split'
                             else 'INERTDEEP', 'params': (kk,),
                             'sigma': sg,
                             'vd': u if R.kind == 'Zp' else None})
                return base
            # refinement at depth kk with letter zb != 0
            assert not K.is_zero(zb)
            s = R.mul(R.lift(zb), pipow(kk))
            A0 = R.add(R.add(R.mul(s, s), R.mul(A1, s)), A0)
            A1 = R.add(A1, R.add(s, s))
            hist.append(kk)
            continue
        # u = None: a0-part vanishes in the window
        if w is not None and 2 * w + 1 <= N:
            base.update({'kind': 'SPLIT-TAIL', 'params': (w,),
                         'sigma': 'split',
                         'vd': 2 * w if R.kind == 'Zp' else None})
            return base
        base.update({'kind': 'UNDECIDED', 'params': (), 'sigma': None,
                     'vd': None, 'w': w})
        return base


